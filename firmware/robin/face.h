// Returns MOOD_COUNT when the name is unknown.
inline Mood moodFromName(const char *name) {
  for (uint8_t i = 0; i < MOOD_COUNT; i++) {
    if (strcmp(name, MOOD_NAMES[i]) == 0) return (Mood)i;
  }
  return MOOD_COUNT;
}
