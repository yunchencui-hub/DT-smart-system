// Writes review/script.md: everything the viewer will hear and see, generated from the video's own data
// (src/script/scenes.ts, src/data/wiring.ts, src/script/order.ts), for the safety review.
// It also enforces the cable rules (exit code 1 if one is broken):
//   R1 nothing is wired while the Arduino USB is plugged in (or the module is on its micro-USB)
//   R2 every scene that plugs in ends unplugged
//   R3 the module goes on micro-USB only while its Gravity cable is not yet connected
//   R4 the capacitor is placed, and its stripe is checked, before the first plug-in after it
//   R5 every bench item is added exactly once, in the step it belongs to (not for the debugging guide: its bench is built)
// and for the debugging guide (--script debug): D1 wiring fixes with the cable out, D2 a test after every fix,
// D3 a faulty part is pointed at before it is swapped
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { ITEMS, PINMAP_ROWS, endName, item } from '../src/data/wiring';
import { ORDER, ORDER_TOTAL } from '../src/script/order';
import { isSay, lineAdds, sayText, SceneDef, Usb } from '../src/script/types';
import { sentences, speakify } from '../src/script/speak';
import { FAULT_ITEMS } from '../src/anatomy/faults';
import { videoArg, VIDEOS } from './videos';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, '..');
// --script anatomy | debug: review an anatomy + ELI5 video instead (scripts/videos.ts) -> review/<name>-script.md
const NAMED = videoArg(), VIDEO = VIDEOS[NAMED];
const ANATOMY = NAMED !== 'guide', DEBUG = NAMED === 'debug';
const guide = await import('../src/script/scenes');
const SCENES: SceneDef[] = await VIDEO.scenes();
const TROUBLE_ROWS = ANATOMY ? [] : guide.TROUBLE_ROWS;
const out: string[] = [];
const w = (s = '') => out.push(s);
const errors: string[] = [];

const legsText = (id: string) => {
  const it = item(id);
  if ('legs' in it) return Object.entries(it.legs).map(([k, h]) => `${k}: ${h.r.length === 2 ? `${h.r[0] === '+' ? '+' : '−'} rail (col ${h.c})` : `column ${h.c}, row ${h.r}`}`).join('; ');
  if (it.kind === 'wire') return `${it.wire}, ${it.color}: ${endName(it.from)} → ${endName(it.to)}`;
  return 'off the breadboard';
};

w(DEBUG ? '# Review copy of the Robin anatomy + ELI5 debugging guide (generated)' : ANATOMY ? '# Review copy of the Robin anatomy + ELI5 build video (generated)' : '# Review copy of the Robin build video (generated)');
w();
w(`Generated by \`scripts/review.ts${ANATOMY ? ` --script ${NAMED}` : ''}\` from the same data the video renders (\`${DEBUG ? 'src/anatomy/debug/script.ts' : ANATOMY ? 'src/anatomy/script.ts' : 'src/script/scenes.ts'}\`, \`src/data/wiring.ts\`${DEBUG ? ', `src/anatomy/faults.ts`' : ANATOMY ? '' : ', `src/script/order.ts`'}). **Do not edit by hand.**`);
w('Each spoken line shows the cable state while it is spoken: 🔌 **USB OUT** (Arduino unplugged: the only state in which we wire), ⚡ **USB IN** (testing), 💽 **MICRO** (Arduino unplugged, voice module alone on its micro-USB cable).');
w('"adds" = the parts or wires that appear on the workbench drawing during that line, with their exact holes.');
w();

// ---------- walk the script
let usb: Usb = 'out';
const added = new Map<string, string>();
let capPlacedAt = -1, stripeCheckedAt = -1, idx = 0;
for (const s of SCENES) {
  w(`## ${s.step ? s.step + ' · ' : ''}${s.title}  \`${s.id}\``);
  w(`*${s.part}*`);
  w();
  let pluggedInScene = false;
  // debugging guide: the fault this case starts from, and the D-rules' bookkeeping
  const fault = (s as SceneDef & { fault?: { show: string[]; hide: string[] } }).fault;
  if (fault) {
    for (const id of fault.show) w(`- *fault shown:* \`${id}\`: ${FAULT_ITEMS.find((f) => f.id === id)?.desc ?? '(unknown fault item!)'}`);
    for (const id of fault.hide) w(`- *hidden until the fix:* \`${id}\`: ${ITEMS.find((f) => f.id === id)?.desc ?? '(unknown item!)'}`);
    for (const id of fault.show) if (!FAULT_ITEMS.some((f) => f.id === id)) errors.push(`D0 ${s.id}: fault item "${id}" is not in src/anatomy/faults.ts`);
    for (const id of fault.hide) if (!ITEMS.some((f) => f.id === id)) errors.push(`D0 ${s.id}: "${id}" is not an item of src/data/wiring.ts`);
    w();
  }
  let firstFix = -1, testedAfterFix = false, blamed = false;
  s.lines.forEach((l, i) => {
    idx++;
    if (typeof l !== 'string' && l.usb) {
      if (l.usb === 'in') {
        pluggedInScene = true;
        if (capPlacedAt >= 0 && stripeCheckedAt < capPlacedAt) errors.push(`R4 ${s.id}: plugged in after the capacitor was placed, without a stripe check first`);
      }
      if (l.usb === 'micro' && added.has('grav')) errors.push(`R3 ${s.id}: module on micro-USB while its Gravity cable is connected`);
      usb = l.usb;
    }
    const badge = usb === 'out' ? '🔌 USB OUT' : usb === 'in' ? '⚡ USB IN' : '💽 MICRO';
    if (isSay(l)) {
      const cap = sayText(l);
      // R1b: no hands-on fixing while the cable is in (a GND wire brushing the + rail is a short)
      if (usb === 'in' && /\b(move|connect|rewire|swap|bend|push|turn the|put the|check the capacitor)\b/i.test(cap)) errors.push(`R1 ${s.id}: "${cap.slice(0, 60)}…" asks for hands-on work while USB IN`);
      if (/stripe/i.test(cap) && capPlacedAt >= 0) stripeCheckedAt = idx;
      w(`${i + 1}. [${badge}] ${cap}`);
      const spoken = sentences(typeof l === 'string' ? l : l.speak ?? l.say).map(speakify).join(' ');
      if (spoken !== cap) w(`   - *spoken:* "${spoken}"`);
    } else if ('robin' in l) {
      w(`${i + 1}. [${badge}] 🤖 Robin plays its own clip audio/en/${String(l.robin).padStart(2, '0')}.mp3`);
    } else {
      w(`${i + 1}. [${badge}] ⏸ pause ${l.pause} s: ${l.cap ?? 'Pause the video and think'}`);
    }
    const extra = typeof l === 'string' ? {} : (l as { serial?: string[]; glow?: string[]; doc?: string; fix?: boolean; soft?: boolean; blame?: boolean });
    if (DEBUG) {
      const wiringFix = extra.fix || (extra.doc === 'fix' && !extra.soft);
      if (extra.doc) w(`   - *doctor's step:* ${extra.doc}${extra.fix ? ' (the faulty part is swapped for the right one)' : ''}${extra.soft ? ' (no wiring: software or files)' : ''}`);
      if (wiringFix && usb !== 'out') errors.push(`D1 ${s.id}: a wiring fix while the cable state is ${usb}`);
      if (extra.soft && extra.fix) errors.push(`D1 ${s.id}: a part swap can't be a no-wiring fix`);
      if (extra.blame) blamed = true;
      if (extra.fix && fault?.show.length && !blamed) errors.push(`D3 ${s.id}: the faulty part is swapped before the narrator points at it (blame)`);
      if ((extra.fix || extra.doc === 'fix') && firstFix < 0) firstFix = i;
      if (firstFix >= 0 && i > firstFix && usb === 'in') testedAfterFix = true;
      if (firstFix >= 0 && i === firstFix && usb === 'in' && extra.soft) testedAfterFix = true; // a software fix is tested while plugged in
    }
    if (extra.serial?.length) w(`   - *Serial Monitor shows:* ${extra.serial.map((x) => `\`${x}\``).join(' · ')}`);
    if (extra.glow?.length) w(`   - *glows:* ${extra.glow.join(', ')}`);
    for (const a of lineAdds(l)) {
      const it = item(a);
      if (usb !== 'out') errors.push(`R1 ${s.id}: "${a}" is wired while the cable state is ${usb}`);
      if (added.has(a)) errors.push(`R5 ${s.id}: "${a}" added twice (also in ${added.get(a)})`);
      const stepNo = Number((s.step || '').match(/Step (\d)/)?.[1]);
      if (stepNo !== it.step) errors.push(`R5 ${s.id}: "${a}" belongs to step ${it.step}, added in step ${stepNo}`);
      added.set(a, s.id);
      if (a === 'cap') capPlacedAt = idx;
      w(`   - *adds* \`${a}\`: ${it.desc}. (${legsText(a)})`);
    }
  });
  if (pluggedInScene && usb !== 'out') errors.push(`R2 ${s.id}: the scene plugs in but does not end unplugged`);
  if (DEBUG && s.step && (firstFix < 0 || !testedAfterFix)) errors.push(`D2 ${s.id}: the case has no ${firstFix < 0 ? 'fix' : 'test (plugged in) after its fix'}`);
  const meta = s as SceneDef & { eli5?: string; fig?: { n: number; title: string; hint?: string; readout?: string }; need?: string[] };
  if (meta.fig) w(`\nFigure card: Fig ${meta.fig.n} · ${meta.fig.title}${meta.fig.hint ? ` · hint: ${meta.fig.hint}` : ''}${meta.fig.readout ? ` · readout: ${meta.fig.readout}` : ''}`);
  if (meta.eli5) w(`\nELI5 card: ${meta.eli5}`);
  if (meta.need?.length) w(`\nParts shown (renders): ${meta.need.join(', ')}`);
  if (s.ui && Object.keys(s.ui).length) {
    w();
    w('On-screen text:');
    for (const [k, v] of Object.entries(s.ui)) w(`- \`${k}\`: ${v}`);
  }
  w();
}
if (!DEBUG) for (const it of ITEMS) if (!added.has(it.id)) errors.push(`R5 bench item "${it.id}" is never added in any scene`);

// ---------- tables
w('## Tables shown on screen');
w();
if (!ANATOMY) {
  w('### Order (16 lines, = docs/03)');
  w('| # | SKU | Qty | Part | € each |');
  w('|---|---|---|---|---|');
  for (const l of ORDER) w(`| ${l.n} | ${l.sku} | ${l.qty} | ${l.name}${l.isNew ? ` (**${l.isNew}**)` : ''} | ${l.unit.toFixed(2)} |`);
  w(`\nTotal parts: €${ORDER_TOTAL.toFixed(2)}`);
  w();
}
w('### Pin map (= docs/04)');
w('| From | To | Wire |');
w('|---|---|---|');
for (const r of PINMAP_ROWS) w(`| ${r.join(' | ')} |`);
w();
if (TROUBLE_ROWS.length) {
  w('### Troubleshooting (= docs/04)');
  w('| Symptom | Likely cause | Fix |');
  w('|---|---|---|');
  for (const r of TROUBLE_ROWS) w(`| ${r.join(' | ')} |`);
  w();
}
w('### Every part and wire on the workbench drawing');
w('| id | step | what | where exactly |');
w('|---|---|---|---|');
for (const it of ITEMS) w(`| ${it.id} | ${it.step} | ${it.desc} | ${legsText(it.id)} |`);
w();
w('Drawing notes: the breadboard is drawn with the rail pair next to the Arduino as − inside, + outside, as printed on the drawn board; the video says to follow the red/blue lines printed on the real board. The top rail pair is unused. Modules (PIR, DFR0534, speaker) lie off the board. The DFR0534 is drawn after the board photo in its datasheet (page 2, Voice Module V1.0): Gravity socket T R − + on the left, top holes VCC GND RX TX BUSY, bottom holes ONE DACR DACL SP− SP+, SPK socket on the right. The video says to go by the printed labels.');
w();

// ---------- automatic checks
w('## Automatic checks');
w();
try {
  w(execFileSync('npx', ['tsx', path.join(HERE, 'netcheck.ts'), '--md'], { cwd: ROOT, encoding: 'utf8' }));
} catch (e) {
  const err = e as { stdout?: string };
  w(err.stdout ?? String(e));
  errors.push('netcheck failed (see above)');
}
w();
w(errors.length ? `**Cable-rule check: ${errors.length} problem(s):**\n\n${errors.map((e) => `- ❌ ${e}`).join('\n')}` : DEBUG
  ? '**Cable-rule check: all passed** (R1 nothing moved by hand while plugged in · R2 every test ends unplugged · R3 micro-USB only with the Gravity cable off · D1 every wiring fix with the cable out · D2 every case tests again after its fix · D3 every faulty part is pointed at before it is swapped).'
  : '**Cable-rule check: all passed** (R1 nothing wired or moved while plugged in · R2 every test ends unplugged · R3 micro-USB only with the Gravity cable off · R4 capacitor stripe checked before plug-in · R5 every item added once, in its own step).');

fs.mkdirSync(path.join(ROOT, 'review'), { recursive: true });
const OUT = VIDEO.review;
fs.writeFileSync(path.join(ROOT, OUT), out.join('\n') + '\n');
console.log(`${OUT} written (${out.length} lines)`);
if (errors.length) { console.error(errors.join('\n')); process.exit(1); }
